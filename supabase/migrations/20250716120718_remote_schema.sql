CREATE OR REPLACE FUNCTION public.trigger_lottery_check()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO 'public'
AS $function$
DECLARE
    participant_record RECORD;
    total_reviews INTEGER;
BEGIN
    -- עדכון מספר הביקורות של המשתמש
    INSERT INTO lottery_participants (customer_email, reviews_count, last_review_date)
    VALUES (NEW.customer_email, 1, NEW.created_at)
    ON CONFLICT (customer_email) 
    DO UPDATE SET 
        reviews_count = lottery_participants.reviews_count + 1,
        last_review_date = NEW.created_at;
    
    -- בדיקה אם הגענו ל-500 ביקורות
    SELECT SUM(reviews_count) INTO total_reviews FROM lottery_participants WHERE is_eligible = true;
    
    IF total_reviews >= 500 THEN
        -- בחירת זוכה אקראי
        SELECT * INTO participant_record 
        FROM lottery_participants 
        WHERE is_eligible = true 
        ORDER BY RANDOM() 
        LIMIT 1;
        
        -- הוספת הזוכה לטבלה
        INSERT INTO lottery_winners (customer_email) VALUES (participant_record.customer_email);
        
        -- איפוס הזכאות לכל המשתתפים
        UPDATE lottery_participants SET is_eligible = false;
        
        -- יצירת מחזור חדש
        UPDATE lottery_participants SET is_eligible = true, reviews_count = 0;
    END IF;
    
    RETURN NEW;
END;
$function$
;

