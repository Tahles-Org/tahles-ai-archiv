CREATE OR REPLACE FUNCTION public.is_admin()
 RETURNS boolean
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
BEGIN
  RETURN (
    SELECT EXISTS(
      SELECT 1 
      FROM public.user_roles 
      WHERE user_id = auth.uid() 
      AND role IN ('מנהל-על', 'מנהל') 
      AND is_active = true
    )
  );
END;
