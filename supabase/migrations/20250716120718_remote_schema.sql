CREATE OR REPLACE FUNCTION public.check_service_availability(p_service_id uuid, p_date date, p_start_time time without time zone, p_duration_minutes integer DEFAULT 120, p_location text DEFAULT NULL::text)
 RETURNS boolean
 LANGUAGE plpgsql
 SET search_path TO 'public'
AS $function$
DECLARE
  v_calendar_connected boolean;
  v_calendar_active boolean;
  v_service_areas text[];
  v_setup_time_minutes integer;
  v_teardown_time_minutes integer;
  required_start_time time;
  required_end_time time;
  slot_available boolean := false;
BEGIN
  -- שליפת פרטי השירות והספק
  SELECT 
    p.calendar_connected, 
    p.calendar_active, 
    s.service_areas,
    s.setup_time_minutes,
    s.teardown_time_minutes
  INTO 
    v_calendar_connected, 
    v_calendar_active, 
    v_service_areas,
    v_setup_time_minutes,
    v_teardown_time_minutes
  FROM services s 
  JOIN providers p ON s.provider_id = p.id 
  WHERE s.id = p_service_id;
  
  -- בדיקה שהיומן מחובר ופעיל
  IF NOT (v_calendar_connected AND v_calendar_active) THEN
    RETURN false;
  END IF;
  
  -- בדיקת אזור שירות אם צוין מיקום
  IF p_location IS NOT NULL AND v_service_areas IS NOT NULL THEN
    IF NOT (p_location = ANY(v_service_areas)) THEN
      RETURN false;
    END IF;
  END IF;
  
  -- חישוב זמן התחלה וסיום הנדרש (כולל זמני הכנה)
  required_start_time := p_start_time - (COALESCE(v_setup_time_minutes, 30) || ' minutes')::interval;
  required_end_time := p_start_time + (p_duration_minutes + COALESCE(v_teardown_time_minutes, 15) || ' minutes')::interval;
  
  -- בדיקת זמינות בטבלת הזמינות
  SELECT EXISTS (
    SELECT 1 FROM provider_availability_slots pas
    WHERE pas.service_id = p_service_id
    AND pas.date = p_date
    AND pas.start_time <= required_start_time::time
    AND pas.end_time >= required_end_time::time
    AND pas.is_available = true
    AND pas.current_bookings < pas.max_concurrent_bookings
  ) INTO slot_available;
  
  RETURN slot_available;
END;
$function$
;

CREATE OR REPLACE FUNCTION public.get_current_user_role()
 RETURNS text
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
BEGIN
  RETURN (
    SELECT role
    FROM public.user_roles
